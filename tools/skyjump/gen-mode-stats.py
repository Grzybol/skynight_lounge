"""Regenerates frontend/apps/poc/src/game/skyjump_v2/modeStats.ts from the Stake math files.

RTP = sum(weight * payout/100) / sum(weight) / cost; max win = max(payout)/100 (x bet).
Usage: python -I tools/skyjump/gen-mode-stats.py [math_dir]   (default: stake-upload/math)
"""
import csv, json, sys
from pathlib import Path

root = Path(__file__).resolve().parents[2]
math = Path(sys.argv[1]) if len(sys.argv) > 1 else root / 'stake-upload' / 'math'
index = json.loads((math / 'index.json').read_text())
rows = []
for mode in index['modes']:
    table = [r for r in csv.reader(open(math / mode['weights']))]
    total = sum(float(r[1]) for r in table)
    ev = sum(float(r[1]) * float(r[2]) / 100 for r in table)
    rows.append((mode['name'], mode['cost'], round(ev / total / mode['cost'] * 100, 2), max(float(r[2]) for r in table) / 100))
out = root / 'frontend/apps/poc/src/game/skyjump_v2/modeStats.ts'
lines = ["/**", " * RTP and max win per mode, computed from the Stake math files (index.json + lookUpTable_*.csv).", " * Generated by tools/skyjump/gen-mode-stats.py. Do not edit by hand.", " */",
         "export const V2_MODE_STATS: Record<string, { cost: number; rtpPct: number; maxWinX: number }> = {"]
for name, cost, rtp, mx in rows:
    lines.append(f"\t{name}: {{ cost: {cost}, rtpPct: {rtp}, maxWinX: {int(mx)} }},")
lines.append("};")
out.write_text("\n".join(lines) + "\n", encoding='utf-8')
print(out)
